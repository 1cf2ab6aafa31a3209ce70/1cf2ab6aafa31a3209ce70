#!/usr/bin/env python3
"""Trace every resource a built app packages to a provenance record.

Each packaged file is mapped back to its repository source:

- <Content>_<Content>.bundle/<path> comes from the title's content package,
  <contentPackage>/Sources/<Content>/<path> (check-foundation.py requires the
  reviewed `.copy("Resources")` rule);
- <lang>.lproj/Localizable.strings(dict) comes from <title>/Localizable.xcstrings;
- any other file at the bundle root comes from the same name in the title
  directory.

The asset catalog compiles to Apple-generated outputs (Assets.car and the
AppIcon renditions), which are not mapped directly; every image in the title's
Assets.xcassets is checked as a source instead, so the icon cannot escape the
trace.

A source is covered when a Markdown link in docs/asset-provenance.md or the
title's CONTENT.md resolves to that file or to a directory containing it. A
packaged file is third-party when its name marks a notice or license
(NOTICE, LICENSE, COPYING, ATTRIBUTION, CREDITS) or a sentence linking it
mentions third-party, upstream, adapted or public-domain origin. A
third-party file needs a linking sentence that names its license (MIT,
Apache, BSD, GPL, LGPL, MPL, ISC, zlib, CC0, CC BY, OFL, Unlicense or public
domain) and its attribution requirement (attribution, notice or credit).
"""
import argparse
import json
from pathlib import Path
import re
import sys

# Generated by Xcode, actool, SwiftPM or code signing; nothing authored ships in them.
APPLE_GENERATED = [
    (re.compile(r"Info\.plist"), "Info.plist generated from build settings"),
    (re.compile(r"PkgInfo"), "bundle type marker"),
    (re.compile(r"Assets\.car"), "compiled asset catalog (sources checked in Assets.xcassets)"),
    (re.compile(r"AppIcon[^/]*\.png"), "app icon renditions compiled from Assets.xcassets"),
    (re.compile(r"_CodeSignature/.*"), "code signature"),
    (re.compile(r"embedded\.mobileprovision"), "provisioning profile"),
    (re.compile(r"[^/]+\.storyboardc/.*|[^/]+\.nib(/.*)?"), "compiled interface files"),
    (re.compile(r"[^/]+\.bundle/Info\.plist"), "resource bundle Info.plist generated by SwiftPM"),
    (re.compile(r"SC_Info/.*"), "App Store encryption info"),
]
# Authored declarations that other gates check field by field rather than provenance records.
REVIEWED_DECLARATIONS = {"PrivacyInfo.xcprivacy": "privacy manifest, checked by check-app-bundle.py and check-foundation.py"}
NOTICE_NAME = re.compile(r"(NOTICE|LICEN[CS]E|COPYING|ATTRIBUTION|CREDITS)", re.IGNORECASE)
THIRD_PARTY = re.compile(r"third[- ]party|upstream|\badapt(s|ed|ation)?\b|public[- ]domain|licensed from", re.IGNORECASE)
LICENSE = re.compile(r"\b(MIT|Apache|BSD|L?GPL|MPL|ISC|zlib|CC0|CC[- ]BY[\w.-]*|OFL|SIL Open Font|Unlicense)\b"
                     r"|public[- ]domain", re.IGNORECASE)
ATTRIBUTION = re.compile(r"attribution|notice|credit", re.IGNORECASE)
LINK = re.compile(r"\[[^\]]*\]\(([^)\s]+)\)")
SENTENCE = re.compile(r"(?<=[.!?])\s+(?=[A-Z\[`])")


def records(root, title_dir):
    """(document, sentence, covered paths) for every sentence with a local link."""
    found = []
    for document in [root / "docs" / "asset-provenance.md", title_dir / "CONTENT.md"]:
        if not document.is_file():
            continue
        for line in document.read_text().splitlines():
            for sentence in SENTENCE.split(line):
                targets = []
                for target in LINK.findall(sentence):
                    if re.match(r"[a-z]+:", target) or target.startswith("#"):
                        continue
                    targets.append((document.parent / target.split("#", 1)[0]).resolve())
                if targets:
                    found.append((document.relative_to(root), sentence.strip(), targets))
    return found


def covering(record_list, source):
    return [(document, sentence) for document, sentence, targets in record_list
            if any(source == target or target in source.parents for target in targets)]


def source_for(relative, title_dir, content_package):
    parts = relative.parts
    product = Path(content_package).name
    if parts[0] == f"{product}_{product}.bundle":
        return content_package / "Sources" / product / Path(*parts[1:])
    if parts[0].endswith(".lproj") and re.fullmatch(r"Localizable\.stringsdict|Localizable\.strings", parts[-1]):
        return title_dir / "Localizable.xcstrings"
    if len(parts) == 1:
        return title_dir / parts[0]
    return None


def check(app, root, target=None):
    target = target or app.stem
    title_dir = root / "Games" / target
    manifest = json.loads((title_dir / "title.json").read_text())
    content_package = root / manifest["contentPackage"]
    executable = app / app.stem
    record_list = records(root, title_dir)
    report = {"app": app.name, "records": len(record_list), "files": {}, "excluded": {}, "problems": []}
    problems = report["problems"]
    if not (title_dir / "CONTENT.md").is_file():
        problems.append(f"{title_dir.relative_to(root)}: missing CONTENT.md provenance record")

    sources = []
    for path in sorted(app.rglob("*")):
        if not path.is_file() or path == executable:
            continue
        relative = path.relative_to(app)
        key = relative.as_posix()
        reason = next((why for pattern, why in APPLE_GENERATED if pattern.fullmatch(key)), None) or REVIEWED_DECLARATIONS.get(key)
        if reason:
            report["excluded"][key] = reason
            continue
        source = source_for(relative, title_dir, content_package)
        if source is None or not source.is_file():
            problems.append(f"{app.name}/{key}: packaged file has no repository source "
                            f"({source.relative_to(root) if source else 'unmapped location'})")
            continue
        sources.append((f"{app.name}/{key}", source))
    catalog = title_dir / "Assets.xcassets"
    for image in sorted(catalog.rglob("*")) if catalog.is_dir() else []:
        if image.is_file() and image.suffix.lower() in {".png", ".jpg", ".jpeg", ".pdf", ".svg", ".heic"}:
            sources.append((f"{app.name}/Assets.car <- {image.relative_to(root)}", image))

    for label, source in sources:
        covers = covering(record_list, source)
        third_party = bool(NOTICE_NAME.search(source.name)) or any(THIRD_PARTY.search(s) for _, s in covers)
        entry = {"source": str(source.relative_to(root)), "records": sorted({str(d) for d, _ in covers}),
                 "thirdParty": third_party}
        report["files"][label] = entry
        if not covers:
            problems.append(f"{label}: no provenance record links {source.relative_to(root)} or a directory containing it")
            continue
        if third_party and not any(LICENSE.search(s) and ATTRIBUTION.search(s) for _, s in covers):
            problems.append(f"{label}: third-party material, but no record sentence linking it names both its license and "
                            f"its attribution requirement (records: {', '.join(entry['records'])})")
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("app", type=Path, help="Built .app bundle")
    parser.add_argument("--title", help="Title target (default: the app's name)")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1], help="Repository root")
    args = parser.parse_args()
    app = args.app.resolve()
    if not app.is_dir() or app.suffix != ".app":
        parser.error("expected a built .app directory")
    try:
        report = check(app, args.root.resolve(), args.title)
    except (OSError, KeyError, json.JSONDecodeError) as error:
        print(f"Asset provenance check failed: {error}", file=sys.stderr)
        return 1
    print(json.dumps(report, indent=2, sort_keys=True))
    if report["problems"]:
        print("Asset provenance check failed:\n  " + "\n  ".join(report["problems"]), file=sys.stderr)
        return 1
    third = sum(1 for entry in report["files"].values() if entry["thirdParty"])
    print(f"Asset provenance check passed for {app.name}: {len(report['files'])} packaged source(s) traced, "
          f"{third} third-party with license and attribution, {len(report['excluded'])} Apple-generated or reviewed "
          "declaration file(s) excluded")
    return 0


if __name__ == "__main__":
    sys.exit(main())
